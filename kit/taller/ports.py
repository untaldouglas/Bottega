"""Puertos mínimos; dominio no conoce filesystem ni transporte."""
from typing import Protocol, Any
class ActionExecutor(Protocol):
    def execute(self, request: dict) -> dict: ...
class Clock(Protocol):
    def now(self) -> str: ...
class CaseRepository(Protocol):
    def load(self, initiative_id: str) -> dict | None: ...
    def save(self, initiative_id: str, snapshot: dict) -> None: ...
